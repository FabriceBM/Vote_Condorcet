"""Package the LaTeX sources for Overleaf: overleaf.zip at the repository root (not committed, see .gitignore).

The zip holds what the three LaTeX documents need, and nothing else:
    main.tex, latexmkrc, journals/            the note (Overleaf's main document: main.tex)
    manuscript/  (.tex, .bib, figures/)       its content
    outputs/tables/*.tex, outputs/figures/*.pdf
    summaries/   (.tex, latexmkrc)            the executive summaries, English and French
    OVERLEAF.md                               which file to set as main document for each
Only files tracked by git are included, so nothing local or generated on the side slips in.

How Overleaf compiles: from the project root it runs
    latexmk -cd -jobname=output -auxdir=<root> -outdir=<root> -synctex=1 -interaction=batchmode -f -pdf <main>
that is, in the main document's folder, with the output in the project root. pdfLaTeX looks for the main file
in the output folder first, so only the note may be called main.tex: a summary called main.tex would
compile the note. Every path in the documents works from the root and from the document's folder, with or
without latexmkrc.

Run from the repository root:
    python3 tools/overleaf_zip.py           # writes overleaf.zip
    python3 tools/overleaf_zip.py --test    # also unpacks it and compiles each document with Overleaf's
                                            # command, with and without the root latexmkrc, and checks that
                                            # the file compiled is the one chosen (needs latexmk)
"""
import fnmatch
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile

OUT = "overleaf.zip"
INCLUDE = ["main.tex", "latexmkrc", "journals/*", "manuscript/*.tex", "manuscript/*/*.tex", "manuscript/*.bib",
           "manuscript/figures/*", "outputs/tables/*.tex", "outputs/figures/*.pdf", "summaries/*.tex",
           "summaries/*/*.tex", "summaries/*/*/*.tex", "summaries/*/*/latexmkrc"]
DOCUMENTS = ["main.tex", "summaries/en/executive/executive-summary_en.tex", "summaries/fr/executive/synthese_fr.tex"]
README = """# Overleaf project: Vote_Condorcet

Three documents. Choose the main document in Menu > Settings > Main document, compiler pdfLaTeX:

| Main document | Output |
|---|---|
| `main.tex` | The note, "Voting for a consensus with veto rights" (about 36 pages) |
| `summaries/en/executive/executive-summary_en.tex` | Executive summary, English (2 pages) |
| `summaries/fr/executive/synthese_fr.tex` | Synthèse, français (2 pages) |

Only the note is called `main.tex`: Overleaf writes its output to the project root, where pdfLaTeX looks
first for the main file, so any other document called `main.tex` would compile the note. Tables and figures in
`outputs/` are generated by the Python scripts of the repository (github.com/FabriceBM/Vote_Condorcet),
not on Overleaf: edit the text here, the numbers in the repository.

Built from commit {commit}.
"""


def tracked():
    return subprocess.run(["git", "ls-files"], capture_output=True, text=True, check=True).stdout.split()


def build():
    files = [f for f in tracked() if any(fnmatch.fnmatch(f, p) for p in INCLUDE)
             and not f.endswith("/.gitkeep")]
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(files):
            z.write(f)
        z.writestr("OVERLEAF.md", README.replace("{commit}", commit))
    print(f"  {OUT}: {len(files) + 1} files, commit {commit}")
    return files


def main_file_compiled(fls):
    """The first .tex file pdfLaTeX opened, from its recorder file: the main file it actually compiled."""
    pwd = ""
    for line in open(fls, encoding="utf8", errors="replace"):
        if line.startswith("PWD "):
            pwd = line[4:].strip()
        elif line.startswith("INPUT ") and line.strip().endswith(".tex"):
            return os.path.realpath(os.path.join(pwd, line[6:].strip()))
    return ""


def test():
    """Unpack and compile each document with Overleaf's command, with and without the root latexmkrc."""
    if not shutil.which("latexmk"):
        print("  latexmk not found")
        return False
    ok = True
    for keep_rc in (True, False):
        print(f"  {'with' if keep_rc else 'without'} the root latexmkrc")
        for doc in DOCUMENTS:
            with tempfile.TemporaryDirectory() as d:
                d = os.path.realpath(d)
                with zipfile.ZipFile(OUT) as z:
                    z.extractall(d)
                if not keep_rc:
                    os.remove(os.path.join(d, "latexmkrc"))
                cmd = ["latexmk", "-cd", "-jobname=output", f"-auxdir={d}", f"-outdir={d}", "-synctex=1",
                       "-interaction=batchmode", "-f", "-pdf", os.path.join(d, doc)]
                code = subprocess.run(cmd, cwd=d, capture_output=True, text=True).returncode
                log = open(os.path.join(d, "output.log"), encoding="latin-1").read()
                compiled = main_file_compiled(os.path.join(d, "output.fls"))
                problems = [p for p, bad in (
                    (f"exit {code}", code != 0),
                    ("compiled " + os.path.relpath(compiled, d), compiled != os.path.join(d, doc)),
                    ("LaTeX error", "\n! " in log),
                    ("undefined references", "undefined" in log),
                    ("file not found", "not found" in log)) if bad]
                ok &= not problems
                print(f"    {doc:<48} {'ok' if not problems else 'FAILED: ' + '; '.join(problems)}")
    return ok


if __name__ == "__main__":
    build()
    if "--test" in sys.argv:
        print("Compiling each document as Overleaf does (latexmk -cd, output in the project root)")
        sys.exit(0 if test() else 1)
