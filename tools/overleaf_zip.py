"""Package the LaTeX sources for Overleaf: overleaf.zip at the repository root (not committed, see .gitignore).

The zip holds what the three LaTeX documents need, and nothing else:
    main.tex, latexmkrc, journals/            the note (Overleaf's main document: main.tex)
    manuscript/  (.tex, .bib, figures/)       its content
    outputs/tables/*.tex, outputs/figures/*.pdf
    summaries/   (.tex, latexmkrc)            the executive summaries, English and French
    OVERLEAF.md                               which file to set as main document for each
Only files tracked by git are included, so nothing local or generated on the side slips in.

Overleaf compiles from the project root whatever the main document, and may ignore latexmkrc: every path in
the documents works from the root without it (see main.tex and summaries/<lang>/executive/main.tex).

Run from the repository root:
    python3 tools/overleaf_zip.py           # writes overleaf.zip
    python3 tools/overleaf_zip.py --test    # also unpacks it and compiles the three documents from the root,
                                            # without latexmkrc, as Overleaf does (needs pdflatex and bibtex)
"""
import fnmatch
import os
import subprocess
import sys
import tempfile
import zipfile

OUT = "overleaf.zip"
INCLUDE = ["main.tex", "latexmkrc", "journals/*", "manuscript/*.tex", "manuscript/*/*.tex", "manuscript/*.bib",
           "manuscript/figures/*", "outputs/tables/*.tex", "outputs/figures/*.pdf", "summaries/*.tex",
           "summaries/*/*.tex", "summaries/*/*/*.tex", "summaries/*/*/latexmkrc"]
DOCUMENTS = [("main.tex", "main", True), ("summaries/en/executive/main.tex", "summary_en", False),
             ("summaries/fr/executive/main.tex", "synthese_fr", False)]
README = """# Overleaf project: Vote_Condorcet

Three documents. Choose the main document in Menu > Main document, compiler pdfLaTeX:

| Main document | Output |
|---|---|
| `main.tex` | The note, "Voting for a consensus with veto rights" (about 36 pages) |
| `summaries/en/executive/main.tex` | Executive summary, English (2 pages) |
| `summaries/fr/executive/main.tex` | Synthèse, français (2 pages) |

All paths work from the project root, which is where Overleaf compiles. Tables and figures in
`outputs/` are generated by the Python scripts of the repository (github.com/FabriceBM/Vote_Condorcet),
not on Overleaf: edit the text here, the numbers in the repository.

Built from commit {commit}.
"""


def tracked():
    return subprocess.run(["git", "ls-files"], capture_output=True, text=True, check=True).stdout.split()


def build():
    files = [f for f in tracked() if any(fnmatch.fnmatch(f, p) for p in INCLUDE)
             and not f.endswith("/.gitkeep")]
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(files):
            z.write(f)
        z.writestr("OVERLEAF.md", README.replace("{commit}", commit))
    print(f"  {OUT}: {len(files) + 1} files, commit {commit}")
    return files


def test():
    """Unpack and compile each document from the root, without latexmkrc, as Overleaf would."""
    ok = True
    with tempfile.TemporaryDirectory() as d:
        with zipfile.ZipFile(OUT) as z:
            z.extractall(d)
        for f in ("latexmkrc",):                      # Overleaf may ignore it: test without
            os.remove(os.path.join(d, f))
        for doc, job, bib in DOCUMENTS:
            run = lambda *a: subprocess.run(a, cwd=d, capture_output=True, text=True)
            cmd = ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", f"-jobname={job}", doc]
            steps = [cmd] + ([["bibtex", job], cmd, cmd] if bib else [cmd])
            codes = [run(*c).returncode for c in steps]
            log = open(os.path.join(d, f"{job}.log"), encoding="latin-1").read()
            good = not any(codes) and "undefined" not in log and "not found" not in log
            ok &= good
            print(f"  {doc:<34} {'ok' if good else 'FAILED (exit codes ' + str(codes) + ')'}")
    return ok


if __name__ == "__main__":
    build()
    if "--test" in sys.argv:
        print("Compiling from the root without latexmkrc, as Overleaf does")
        sys.exit(0 if test() else 1)
